// =====================================================================
//  فهرست زبان‌های سایت
//  برای اضافه کردن یک زبان جدید:
//    ۱) فایل lang/en.js را کپی کنید و اسمش را بگذارید کد زبان (مثلاً ar.js)
//    ۲) داخل فایل جدید، "en" را به کد زبان جدید تغییر دهید و مقدارها را ترجمه کنید
//    ۳) یک خط برای آن در لیست پایین اضافه کنید — همین! به script.js و index.html
//       هیچ دست‌زدنی لازم نیست؛ منوی انتخاب زبان هم خودکار ساخته می‌شود.
//
//  code   : کد زبان = اسم فایل (ar ← lang/ar.js)
//  label  : اسمی که در منوی انتخاب زبان نمایش داده می‌شود
//  flag   : کد دو حرفی کشور برای پرچم (flagcdn.com) مثل ir, gb, tr, de, sa
//  locale : برای فرمت تاریخ (مثل ar-SA, fa-IR, en-US)
// =====================================================================
window.BUSKIT_LANGUAGES = [
  { code: "fa", label: "فارسی", flag: "ir", locale: "fa-IR" },
  { code: "en", label: "English", flag: "gb", locale: "en-US" },
  { code: "tr", label: "Türkçe", flag: "tr", locale: "tr-TR" },
  { code: "de", label: "Deutsch", flag: "de", locale: "de-DE" },
  { code: "ar", label: "العربية", flag: "sa", locale: "ar-SA" },
];

// زبان پیش‌فرض برای بازدیدکننده‌ای که قبلاً زبانی انتخاب نکرده
window.BUSKIT_DEFAULT_LANG = "tr";

// بعد از ویرایش یکی از فایل‌های زبان، این عدد را یکی زیاد کنید تا مرورگرِ
// بازدیدکننده‌ها نسخه‌ی کهنه‌ی (کش‌شده) فایل را نگه ندارد.
window.BUSKIT_LANG_VERSION = 1;
